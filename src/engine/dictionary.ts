function lemma(word: string): string {
  const lower = word.toLowerCase();
  if (IRREGULARS[lower]) return IRREGULARS[lower];
  if (lower.endsWith('ies') && lower.length > 4) return lower.slice(0, -3) + 'y';
  if (lower.endsWith('ves') && lower.length > 4) return lower.slice(0, -3) + 'f';
  if (lower.endsWith('es') && /(ss|sh|ch|x|zz)es$/.test(lower)) return lower.slice(0, -2);
  if (lower.endsWith('s') && !lower.endsWith('ss') && lower.length > 3) return lower.slice(0, -1);
  if (lower.endsWith('ed') && lower.length > 4) return lower.endsWith('i') ? lower.slice(0, -3) + 'y' : lower.slice(0, -2);
  if (lower.endsWith('ing') && lower.length > 5) { const b = lower.slice(0, -3); return b.endsWith(b[b.length-1]) ? b.slice(0, -1) : b; }
  if (lower.endsWith('er') && lower.length > 4) return lower.slice(0, -2);
  if (lower.endsWith('est') && lower.length > 5) return lower.slice(0, -3);
  if (lower.endsWith("'s")) return lower.slice(0, -2);
  return lower;
}

export function lookupWord(word: string): DictEntry | null {
  const l = lemma(word.toLowerCase());
  return DICT_DATA[l] || DICT_DATA[word.toLowerCase()] || null;
}

export function getPhonetic(word: string): string {
  const entry = lookupWord(word);
  return entry?.phonetic || '';
}

export function getDefinition(word: string): string {
  const entry = lookupWord(word);
  return entry ? `${entry.pos} ${entry.definition}` : '';
}
